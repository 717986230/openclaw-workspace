# 第一章 消失的广播

2029年，深秋。

林远记得外婆去世那天，全城的收音机同时发出了一声尖锐的啸叫。那是凌晨三点十七分，他在城西的公寓里被那种声音惊醒——不是普通的电流杂音，而是一种近乎悲鸣的高频振动，像是有什么东西正在穿过一道看不见的屏障。

那之后的七年里，他再也没有调准过任何频道。

今天是外婆的忌日。林远站在老房子门口，手里攥着那台老旧的收音机。外壳已经被岁月磨得斑驳，但那个铜质的调频旋钮依然完好。外婆说那是太爷爷留下来的，具体多少年了，没人说得清。

"小远，你真的要去？"母亲站在门口，声音里带着担忧。

"我得试试。"他低头看着收音机，"外婆说过，只要我愿意，我就能听见。"

母亲没有再说话。这些年来，她已经习惯了儿子在这件事上的固执。外婆临终前说的那句话她记得——"这孩子是最后一个能听见的人。"

林远推开门，走进那间堆满旧物的房间。灰尘在午后的光线中浮动，他找到了那张老旧的藤椅，坐下来，把收音机放在膝盖上。

外婆曾经坐在这里，数十年如一日，调着那个旋钮，等待某个来自很远很远的地方的声音。

他深吸一口气，慢慢转动调频旋钮。

收音机发出一阵噼啪的杂音，然后是沙沙的白噪音。林远的手指稳稳地移动着，一格一格，像外婆教他的那样。噪音在某个频点突然变得清晰——不是人声，而是一段旋律，钢琴曲，很老的曲子。

然后，声音消失了。

林远皱起眉头，继续转动旋钮。更多杂音涌来，像是无数个频道重叠在一起。他继续找，直到——

"……紧急通知……第三次调频协议已经启动……所有人立刻……"

一个断断续续的女声从收音机里传来，带着严重的失真，像是从很远的地方传来，又像是就在耳边。

林远屏住呼吸。这是七年来他第一次听到清晰的语音。

"……不是演习……维度偏移已经达到临界值……重复，维度偏移已经达到临界值……"

突然，声音变得清晰无比。

"如果你能听见这条消息，请立即联系调频委员会。坐标已经失效，但你可以尝试手动——"

咔嗒一声，所有声音都消失了。

林远愣在原地，心跳加速。窗外的阳光依然温暖，但他的后背却泛起一阵凉意。七年了，他无数次尝试调频，无数次只有死寂。而现在，他听到了真正的消息——关于维度偏移，关于调频委员会，关于某个他从未听说过的紧急协议。

他低头看着手中的收音机。外婆留下的这台老机器，真的只是一台普通的收音机吗？

就在这时，收音机再次发出声音。

这一次不是广播，而是一个低沉的男声，带着某种奇怪的韵律，像是吟诵，又像是某种古老的咒语。

"频率已锁定。第177号观测点，偏移度：12.7%。状态：危险。"

林远的手不自觉地收紧了。

"时间窗口：72小时。是否响应？"

他犹豫了一秒，然后开口："响应。"

收音机发出一声轻响，像是某个开关被打开了。然后，一个温和的女声响起："身份确认：林远，外婆苏婉清的学徒。调频权限：未激活。当前任务：前往第177号观测点，确认偏移源。"

"等等，"林远打断道，"什么是调频权限？为什么我没有？"

"因为你尚未完成觉醒仪式。"那个声音回答，"苏婉清女士在去世前申请了遗嘱激活程序，但你从未执行。"

林远想起外婆去世前的那个夜晚。她握着他的手，说的那些他当时听不懂的话。"小远，总有一天你会需要它。""当你准备好的时候，去老房子，打开收音机。""你会听见该听见的。"

当时他以为那只是临终的胡话。

"觉醒仪式在哪里？"他问。

"你已经在仪式地点。"

林远环顾四周。这间老房子，这些旧物，外婆坐了几十年的藤椅——

"苏婉清女士选择在这里完成仪式，"收音机里的声音说，"因为这里是177号观测点的核心。只有从这里出发，才能准确抵达偏移点。"

"等等，抵达？你是说离开这里？"

"调频不仅仅是接收，林远先生。调频是双向通道。你外婆花了三十年才理解这一点。"

林远沉默了。外婆的一生在他脑海中浮现——一个普通的退休教师，却总是不停地摆弄那台收音机。小时候他以为那只是老人的习惯，现在看来……

"我该怎么做？"他终于问道。

"把收音机贴近胸口。"

林远照做了。老旧的金属外壳传来一阵微微的温热，像是有什么东西在里面苏醒。

"现在，想象一个画面。你见过的最清晰的画面。不是用眼睛看到的，而是用记忆记住的。"

他想到了外婆的脸。那是去年生日时拍的照片，外婆站在这间屋子里，背后是那排旧书架。她在笑，眼角的皱纹像是年轮。

"很好。现在，把注意力集中在调频旋钮上。不是转动它，而是感受它。感受它的阻尼，它的重量，它存在的意义。"

林远闭上眼睛。旋钮的触感在指尖变得异常清晰——黄铜的冰凉，细密的齿轮纹路，还有某种说不清道不明的……脉动。像是心跳，又像是某种频率正在通过这个小小的金属物件与他共振。

"你感觉到了。"那个声音说，似乎带着一丝欣慰，"那就是你的频率。每个人都有自己的频率，就像每个人都有自己的指纹。苏婉清女士的频率是第177号。现在，那是你的了。"

林远睁开眼睛。他发现自己还坐在藤椅上，窗外的阳光已经变成了橘红色。不知不觉间，几个小时过去了？

"觉醒仪式完成，"收音机宣布，"你的调频权限已激活。任务已更新：前往第177号观测点的偏移源，阻止维度崩塌。时限：72小时。"

"等等，维度崩塌是什么意思？"

"字面意思。两个维度之间的边界正在消融。如果不阻止，177号观测点所代表的整个现实将与其他维度混合，届时所有存在于此的事物都将……"

"都将怎样？"

"不复存在。"

林远站起身，收音机还贴在胸口。他低头看着这个陪伴他长大的老物件，第一次真正理解了外婆为什么如此执着。

"我该从哪里开始？"他问。

"出门右转，第三个路口有一家旧货店。店主知道该去哪里。"

"就这样？没有地图？没有更多信息？"

"调频师的任务从来不是被告知该怎么做，"那个声音回答，"而是自己找到答案。这是你外婆教给你的第一课，不是吗？"

林远想起小时候，外婆教他调收音机的情景。"不要问该往哪转，"她总是说，"用耳朵去找。"当时他以为那只是比喻。

"我会找到的。"他说完，收起收音机，走向门口。

推开门的瞬间，夕阳的余晖洒在他脸上。他回头看了一眼老房子——那扇窗户，藤椅的位置，外婆的身影仿佛还在那里。

"外婆，"他轻声说，"我终于听见了。"

然后他转身，走进即将被暮色吞没的街道，朝着那个旧货店的方向走去。

他知道，从这一刻起，一切都不同了。

他不再是一个普通的年轻人，而是一个调频师——一个能够跨越维度的信使，一个手握现实裂缝钥匙的人。

而72小时后，要么他阻止了这场灾难，要么整个世界将与他所知道的一切一同消失。

